/**
 * Reusable modifier providing translucent glass surfaces with a specular highlight and crisp border.
 */
@Stable
fun Modifier.glassSurface(
    shape: Shape = RoundedCornerShape(NuvioTokens.Radius.card),
    backgroundColor: Color = Color(0xFF11182B).copy(alpha = NuvioTokens.Glass.defaultAlpha),
    borderColor: Color = NuvioTokens.Glass.borderColor,
    borderWidth: Dp = NuvioTokens.Glass.borderWidth,
    hasGradientOverlay: Boolean = true,
    elevation: Dp = 0.dp,
): Modifier {
    val surfaceAlpha = backgroundColor.alpha.coerceIn(
        NuvioTokens.Glass.alphaSurfaceMin,
        NuvioTokens.Glass.alphaSurfaceMax,
    )
    val translucentBackground = backgroundColor.copy(alpha = surfaceAlpha)

    return this
        .shadow(elevation, shape)
        .clip(shape)
        .background(translucentBackground)
        .then(
            if (hasGradientOverlay) {
                Modifier.background(
                    Brush.verticalGradient(
                        colors = listOf(
                            Color.White.copy(alpha = 0.22f),
                            Color.White.copy(alpha = 0.04f),
                        ),
                    ),
                )
            } else {
                Modifier
            },
        )
        .border(borderWidth, borderColor, shape)
}

fun Modifier.ambientGlassBackdrop(): Modifier = drawBehind {
    val maxDimension = maxOf(size.width, size.height)
    drawRect(Color(0xFF070913), size = size)
    drawRect(
        brush = Brush.radialGradient(
            colorStops = arrayOf(
                0f to Color(0xFF263F91).copy(alpha = 0.46f),
                0.34f to Color(0xFF27347E).copy(alpha = 0.28f),
                0.72f to Color(0xFF1A214C).copy(alpha = 0.1f),
                1f to Color.Transparent,
            ),
            center = Offset(size.width * 0.08f, size.height * 0.08f),
            radius = maxDimension * 0.82f,
        ),
        size = size,
    )
    drawRect(
        brush = Brush.radialGradient(
            colorStops = arrayOf(
                0f to Color(0xFF6241A2).copy(alpha = 0.34f),
                0.38f to Color(0xFF46327F).copy(alpha = 0.21f),
                0.76f to Color(0xFF282044).copy(alpha = 0.07f),
                1f to Color.Transparent,
            ),
            center = Offset(size.width * 0.92f, size.height * 0.28f),
            radius = maxDimension * 0.7f,
        ),
        size = size,
    )
    drawRect(
        brush = Brush.radialGradient(
            colorStops = arrayOf(
                0f to Color(0xFF243E83).copy(alpha = 0.22f),
                0.42f to Color(0xFF1B2B63).copy(alpha = 0.12f),
                1f to Color.Transparent,
            ),
            center = Offset(size.width * 0.68f, size.height * 0.98f),
            radius = maxDimension * 0.66f,
        ),
        size = size,
    )
}

/**
 * Reusable GlassCard component implementing Jetpack Compose Glassmorphism design system.
 */
@Composable
fun GlassCard(
    modifier: Modifier = Modifier,
    shape: Shape = RoundedCornerShape(NuvioTokens.Radius.card),
    backgroundColor: Color = Color(0xFF11182B).copy(alpha = NuvioTokens.Glass.defaultAlpha),
    borderColor: Color = NuvioTokens.Glass.borderColor,
    borderWidth: Dp = NuvioTokens.Glass.borderWidth,
    elevation: Dp = 0.dp,
    onClick: (() -> Unit)? = null,
    content: @Composable () -> Unit,
) {
    val glassModifier = modifier.glassSurface(
        shape = shape,
        backgroundColor = backgroundColor,
        borderColor = borderColor,
        borderWidth = borderWidth,
        hasGradientOverlay = true,
        elevation = elevation,
    )

    if (onClick != null) {
        Surface(
            modifier = glassModifier.clickable(onClick = onClick),
            color = Color.Transparent,
            shape = shape,
            content = content,
        )
    } else {
        Box(
            modifier = glassModifier,
            content = content,
        )
    }
}

@Composable
fun NuvioTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    appTheme: AppTheme = AppTheme.WHITE,
    amoled: Boolean = false,
    customThemeColors: CustomThemeColors = CustomThemeColors.Default,
    content: @Composable () -> Unit,
) {
    val palette = remember(appTheme, customThemeColors) {
        ThemeColors.getColorPalette(appTheme, customThemeColors)
    }
    val colorScheme = buildColorScheme(palette, amoled = amoled)
    val tokens = defaultNuvioThemeTokens(palette, amoled = amoled, colorScheme = colorScheme)

    val density = LocalDensity.current
    CompositionLocalProvider(
        LocalDensity provides Density(
            density = density.density,
            fontScale = 1f,
        ),
        LocalNuvioThemeTokens provides tokens,
        LocalNuvioTypeScale provides NuvioTypeTokens,
        LocalRippleConfiguration provides NuvioRippleConfiguration,
        LocalAppTheme provides appTheme,
        LocalThemePalette provides palette,
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = NuvioTypography,
        ) {
            SkeletonAnimationProvider(content = content)
        }
    }
}
